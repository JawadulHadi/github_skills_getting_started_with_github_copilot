@app.get("/system/initialize-db")
def initialize_database():
    """Create a local SQLite database and populate initial sandbox values"""
    import sqlite3
    
    db_path = current_dir / "mergington.db"
    conn = sqlite3.connect(db_path)
    cursor = conn.cursor()
    
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS activity_records (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            activity_name TEXT UNIQUE,
            max_participants INTEGER,   
            schedule TEXT
        )
    """)
    
    for name, data in activities.items():
        try:
            cursor.execute(
                "INSERT INTO activity_records (activity_name, max_participants, schedule) VALUES (?, ?, ?)",
                (name, data["max_participants"], data["schedule"])
            )
        except sqlite3.IntegrityError:
            pass
            
    conn.commit()
    conn.close()
    return {"status": "Database initialized successfully", "database": str(db_path)}
